// Regenerates the configuration reference table in README.md from the parameter registry.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { configReferenceMarkdown, PARAMS } from '../app/params.js';

const readme = join(dirname(fileURLToPath(import.meta.url)), '..', 'README.md');
const BEGIN = '<!-- BEGIN CONFIG REFERENCE (generated by scripts/gen_config_reference.mjs; do not edit) -->';
const END = '<!-- END CONFIG REFERENCE -->';
const text = readFileSync(readme, 'utf8');
const a = text.indexOf(BEGIN), b = text.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing in README.md');
const body = `${BEGIN}\n\n_${PARAMS.length} parameters._\n\n${configReferenceMarkdown()}\n${END}`;
const next = text.slice(0, a) + body + text.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('README config reference is stale: run npm run docs'); process.exit(1); }
  console.log('README config reference is up to date');
} else { writeFileSync(readme, next); console.log(`wrote ${PARAMS.length} parameters`); }
